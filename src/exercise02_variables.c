#include <stdio.h>

int main(void)
{
    int studentAge = 21;
    float piValue = 3.14f;
    double eValue = 2.718281;
    char grade = 'A';

    printf("Integer value: %d\n", studentAge);
    printf("Float value: %f\n", piValue);
    printf("Double value: %lf\n", eValue);
    printf("Character value: %c\n", grade);

    return 0;
}