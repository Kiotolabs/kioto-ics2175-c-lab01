#include <stdio.h>

int main(void)
{
    int number = 21;
    float decimalNumber = 3.14f;
    double preciseNumber = 2.718281;
    char letter = 'A';

    printf("Integer value: %d\n", number);
    printf("Float value: %f\n", decimalNumber);
    printf("Double value: %lf\n", preciseNumber);
    printf("Character value: %c\n", letter);

    return 0;
}
